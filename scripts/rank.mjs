#!/usr/bin/env node
// Refresh rankings.json from OpenRouter's unified benchmarks endpoint, which
// aggregates Artificial Analysis, Design Arena and OpenRouter's own GPQA,
// tau-bench and web-search evals.
//
// Usage:
//   OPENROUTER_API_KEY=sk-or-... node scripts/rank.mjs [--task-type code] [--dry]
//
// Without a key this exits non-zero and leaves the vendored prior in place.
// The rate limits are from the endpoint's documentation, not measured here:
// https://openrouter.ai/docs/client-sdks/typescript/sdks/benchmarks/README.md

import { writeFileSync, readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"

const here = dirname(fileURLToPath(import.meta.url))
const target = join(here, "..", "rankings.json")

const key = process.env.OPENROUTER_API_KEY
if (!key) {
  console.error("rank: set OPENROUTER_API_KEY to refresh from OpenRouter benchmarks")
  process.exit(2)
}

const dry = process.argv.includes("--dry")
const taskIndex = process.argv.indexOf("--task-type")
const taskType = taskIndex === -1 ? undefined : process.argv[taskIndex + 1]

const url = new URL("https://openrouter.ai/api/v1/benchmarks")
if (taskType) url.searchParams.set("task_type", taskType)

const response = await fetch(url, {
  headers: { Authorization: `Bearer ${key}`, Accept: "application/json" },
})
if (!response.ok) {
  console.error(`rank: ${response.status} ${response.statusText}`)
  console.error((await response.text()).slice(0, 500))
  process.exit(1)
}

const body = await response.json()

// The response shape is a list of benchmarks, each with per-model scores on a
// 0-1 or 0-100 scale depending on the source. Normalise to 0-100 and keep the
// best score seen per model across benchmarks.
const rows = []
const visit = (node) => {
  if (Array.isArray(node)) return node.forEach(visit)
  if (!node || typeof node !== "object") return
  const id = node.model ?? node.model_id ?? node.slug ?? node.id
  const score = node.score ?? node.accuracy ?? node.value ?? node.quality
  if (typeof id === "string" && typeof score === "number") {
    rows.push({ id, score: score <= 1 ? score * 100 : score })
  }
  for (const value of Object.values(node)) visit(value)
}
visit(body)

const best = new Map()
for (const row of rows) {
  const current = best.get(row.id)
  if (current === undefined || row.score > current) best.set(row.id, row.score)
}

if (best.size === 0) {
  console.error("rank: no model scores found in the response, leaving the file untouched")
  process.exit(1)
}

// Wildcards so a future 4.2 inherits the family's place until it has its own score.
const rank = {}
for (const [id, score] of [...best.entries()].sort((a, b) => b[1] - a[1])) {
  const slug = id.includes("/") ? id.split("/").slice(1).join("/") : id
  rank[`*${slug}*`] = Math.round(score * 10) / 10
}

const out = {
  _note: "Generated by scripts/rank.mjs from OpenRouter's unified benchmarks. Scores are 0-100, best seen per model, wildcarded by family.",
  _updated: new Date().toISOString().slice(0, 10),
  rank,
}

if (dry) {
  console.log(JSON.stringify(out, null, 2))
} else {
  const existing = JSON.parse(readFileSync(target, "utf8"))
  writeFileSync(target, `${JSON.stringify({ ...existing, ...out }, null, 2)}\n`)
  console.log(`rank: wrote ${Object.keys(rank).length} families to ${target}`)
}
